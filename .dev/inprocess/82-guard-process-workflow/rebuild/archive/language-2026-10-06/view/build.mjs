// Builds each document into ONE self-contained file that renders in the browser.
//
// The YAML is read here, at build time, and written out as a data module. Everything
// else — the typing, the components, React itself — is bundled and runs in the page. There
// is no server render: what you open is what React drew.
import { build } from 'esbuild'
import { writeFileSync, readFileSync } from 'node:fs'
import yaml from 'js-yaml'

const here = new URL('.', import.meta.url).pathname
const read = (f) => yaml.load(readFileSync(here + '../' + f, 'utf8'))

const data = {
  metaLanguage: read('meta-language.yaml'),
  language: read('language.yaml'),
  architecture: read('architecture.yaml'),
  contract: read('contract.yaml'),
  setup: read('setup.yaml'),
  highlight: read('highlight.yaml') ?? [],
}
writeFileSync(here + '.data.mjs',
  '// GENERATED by view/build.mjs from the YAML. Never edit.\n' +
  Object.entries(data).map(([k, v]) => `export const ${k} = ${JSON.stringify(v)}\n`).join(''))

const css = readFileSync(here + 'style.css', 'utf8')

// There is no highlight system. The one that was here named a few node kinds by hand and
// each component wrapped itself, so it could only ever mark whole sections, decisions and
// processes — never the one step that actually changed. Rather than leave a flag that
// quietly marks the wrong thing, the flag refuses.
const hlArg = process.argv.find((x) => x.startsWith('--highlight='))
if (hlArg) {
  throw new Error('--highlight is not supported: there is no highlight system yet, and the one that was here could only mark whole sections.')
}

// EVERY declared string in a model file, against the budget for its field. A field with
// no slot of its own falls to `label`, so nothing is unbudgeted. Code is exempt, because a
// word count on a snippet only teaches people to write worse snippets. This is about what
// may be written, so it fails the build; it does not belong on the page.
const SLOT_OF = {
  description: 'description', note: 'aside', statement: 'statement', text: 'assertion',
  question: 'question', why: 'reason', source: 'aside', purpose: 'purpose',
  holds: 'label', never: 'label',
}
const CODE_FIELDS = new Set(['csharp', 'python', 'rust', 'typescript',
  'example', 'equivalents', 'shape', 'locator', 'canonical'])
const slots = Object.fromEntries(data.language.prose.map((x) => [x.id, x]))

const overBudget = []
const walkText = (o, field, path) => {
  if (Array.isArray(o)) return o.forEach((x, i) => walkText(x, field, `${path}[${i}]`))
  if (o && typeof o === 'object') {
    for (const k of Object.keys(o)) walkText(o[k], k, `${path}.${k}`)
    return
  }
  if (typeof o !== 'string' || CODE_FIELDS.has(field)) return
  const slot = SLOT_OF[field] ?? 'label'
  const spec = slots[slot]
  if (!spec) throw new Error(`no prose slot "${slot}" — text that fits no slot is not written`)
  const clean = o.trim().replace(/\s+/g, ' ')
  if (!clean) return
  const n = clean.split(/\s+/).length
  if (n > spec.words) overBudget.push(`${path} is ${n} words, budget ${spec.words} for "${slot}": "${clean.slice(0, 60)}…"`)
}
for (const [name, model] of Object.entries(data)) walkText(model, 'root', name + '.yaml')
if (overBudget.length) {
  console.error(overBudget.map((x) => '  ' + x).join('\n'))
  throw new Error(`${overBudget.length} field(s) over budget`)
}

const DOCS = [
  { id: 'contract', file: 'contract.html', title: 'Contract — issue 82' },
  { id: 'architecture', file: 'architecture.html', title: 'Proposed architecture — issue 82' },
  { id: 'language', file: 'language.html', title: 'The architecture language' },
  { id: 'metaLanguage', file: 'meta-language.html', title: 'The metalanguage' },
]

for (const doc of DOCS) {
  const out = await build({
    entryPoints: [here + 'client.jsx'],
    bundle: true, format: 'iife', platform: 'browser', jsx: 'automatic',
    minify: true, write: false, logLevel: 'warning',
    define: {
      'process.env.NODE_ENV': '"production"',
      __DOC__: JSON.stringify(doc.id),
    },
  })
  const js = out.outputFiles[0].text
  writeFileSync(here + '../' + doc.file, `<!doctype html>
<meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>${doc.title}</title>
<style>${css}</style>
<main id="root"></main>
<script>${js}</script>`)
  console.log(`${doc.file}: ${(js.length / 1024).toFixed(0)}KB, rendered in the browser`)
}
